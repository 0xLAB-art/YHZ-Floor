#!/usr/bin/env python3
"""
e3_fig_tikz.py — emit the E3 effect-size forest plot (figE.tex) from
e3_figure_effects.json (frozen analyzer output). Numbers are transcribed
into the paper verbatim from this generator, same discipline as Table C.

Run:  python3 sp2027/analysis/e3_fig_tikz.py
Out:  sp2027/analysis/e3_rig/figE.tex
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "e3_rig" / "e3_figure_effects.json"
OUT = HERE / "e3_rig" / "figE.tex"

SHORT = {
    "combined": "Combined (median of levels)",
    "build | timer=perf_counter_ns_monotonic": "Timer = perf\\_counter\\_ns",
    "build | timer=getruseru_utime_split": "Timer = getrusage\\_utime",
    "build | cache=cold": "Cache = cold",
    "build | cache=warm": "Cache = warm",
    "build | smt=on": "SMT = on",
    "build | smt=off": "SMT = off",
}


def f3(x: float) -> str:
    return f"{x:.3f}".replace("-0.", "-0.").rstrip("0").rstrip(".") if x != int(x) else f"{x:.0f}"


def main() -> None:
    d = json.loads(SRC.read_text())
    assert d["draft"] is False, "refusing: DRAFT data"
    effects = d["effects"]
    combined = next(e for e in effects if e["contrast"] == "combined")
    comb = combined["effect_ms"]

    rows = []
    for i, e in enumerate(effects, start=1):
        eff = e["effect_ms"]
        lo, hi = e["ci95_ms"]
        # asymmetric explicit errors for pgfplots (x dir=both)
        d_hi = hi - eff
        d_lo = eff - lo
        label = SHORT[e["contrast"]]
        rows.append(
            f"({eff:.3f},{i}) += ({d_hi:.3f},0) -= ({d_lo:.3f},0)"
            f"   % {label}: [{lo:.3f}, {hi:.3f}]")
    coords = "\n".join(rows)
    yticks = ", ".join(str(i) for i in range(1, len(effects) + 1))
    ylabels = ", ".join("{" + SHORT[e["contrast"]] + "}"
                        for e in effects)
    xmin, xmax = -2.35, -1.15

    tex = f"""% AUTO-GENERATED by sp2027/analysis/e3_fig_tikz.py from e3_figure_effects.json
% run_tag=full, draft=false, bootstrap seed {d['seed']} — transcribe verbatim into main.tex
\\begin{{figure}}[!t]
\\centering
\\resizebox{{\\linewidth}}{{!}}{{%
\\begin{{tikzpicture}}
\\begin{{axis}}[width=.96\\linewidth,height=58mm,
 xmin={xmin},xmax={xmax},
 xlabel={{Build effect $\\Delta$median (ms; vulnerable $-$ control) with 95\\% CI}},
 ytick={{{yticks}}},yticklabels={{{ylabels}}},
 y dir=reverse,ymin=.4,ymax={len(effects) + .6},
 xmajorgrids,grid style={{gray!20}},tick label style={{font=\\footnotesize}},
 label style={{font=\\small}}]
% reference: the combined (median-of-levels) effect
\\draw[gray,dashed] (axis cs:{comb:.3f},0.4) -- (axis cs:{comb:.3f},{len(effects) + .6});
% every CI lies strictly below zero: the difference survives every factor level
\\addplot[only marks,mark=*,mark size=1.9pt,color=actblue,
         error bars/.cd,x dir=both,x explicit,error mark=none,error bar style={{color=actblue}}]
coordinates {{
{coords}
}};
\\end{{axis}}
\\end{{tikzpicture}}}}%
\\caption{{E3 per-level build contrasts (vulnerable $-$ constant-time control).
Points are median differences; bars are 10k-resample percentile-bootstrap
95\\% CIs (seed {d['seed']}). The dashed line marks the combined
median-of-levels effect ({comb:.3f}\\,ms). Every factor level agrees in sign
and excludes zero at $\\alpha=0.01$ (dudect-style Welch); the negative
control is null, so the difference is the planted build difference, not an
artifact of timer, cache, or SMT condition.}}
\\label{{fig:effects}}
\\end{{figure}}
"""
    OUT.write_text(tex)
    print(f"wrote {OUT}")
    print(tex)


if __name__ == "__main__":
    main()
