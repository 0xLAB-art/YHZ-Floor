#!/usr/bin/env python3
"""
km_fig.py — generate the KM sensitivity-band TikZ figure for the paper.

Reads bounds_tier_evidence.json (Step 2 of W3_FILL_RUNBOOK.md) and writes
km_band.tex: the tier-1 (outage=censored) survival curve solid, tier-3
(outage=worst-case failure) dashed — the visual envelope of the frozen
sensitivity requirement ("the qualitative conclusions must hold under all
three"). Censoring ticks drawn on the tier-1 curve.

The figure regenerates from a script + raw evidence (number-lock rule):
no hand-typed coordinates. Style follows the paper's existing pgfplots
figures (actblue/actorange, footnotesize ticks, gray grid).

USAGE:
    python3 sp2027/analysis/km_fig.py                     # default paths
    python3 sp2027/analysis/km_fig.py --in EVIDENCE.json --out km_band.tex

Exit: 0 written; 2 = no evidence yet (expected before the W3 fill).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_IN = HERE / "bounds_tier_evidence.json"
DEFAULT_OUT = HERE / "km_band.tex"


def fmt_curve(curve, every_n_ticks=7):
    """curve = [[t, s], ...] → (coordinates string, tick-times list)."""
    pts = " ".join(f"({t:.1f},{s:.4f})" for t, s in curve)
    tick_times = [t for t, _ in curve][::every_n_ticks]
    return pts, tick_times


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="inp", type=Path, default=DEFAULT_IN)
    ap.add_argument("--out", dest="out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    if not args.inp.exists():
        print(f"no evidence yet: {args.inp} (bounds_tier.py fills it at W3)")
        return 2
    ev = json.loads(args.inp.read_text())
    band = ev.get("band") or {}
    t1 = band.get("tier1_outage_censored") or {}
    t3 = band.get("tier3_outage_as_failure") or {}
    c1, ticks1 = fmt_curve(t1.get("curve") or [])
    c3, _ = fmt_curve(t3.get("curve") or [])
    if not c1:
        print("evidence has no tier-1 curve — nothing to draw")
        return 2

    ymax = max(s for _, s in (t1.get("curve") or [[0, 1.0]]))
    xmax = (t1.get("curve") or [[0, 0]])[-1][0] if t1.get("curve") else 1
    xmax = max(xmax, 1.0)

    tex = f"""% km_band.tex — regenerated by analysis/km_fig.py from bounds_tier_evidence.json
% Tier 1: outage = censored (solid)   Tier 3: outage = worst-case failure (dashed)
% Frozen requirement: qualitative conclusions hold under ALL THREE tiers
% (tier 2, the Fine-Gray competing-risk view, is reported in the text).
\\begin{{figure}}[t]
\\centering
\\resizebox{{\\linewidth}}{{!}}{{%
\\begin{{tikzpicture}}
\\begin{{axis}}[width=.96\\linewidth,height=58mm,
 xmin=0,xmax={xmax:.0f},ymin=0,ymax=1.02,
 xlabel={{Time to verdict (s)}},ylabel={{Survival $S(t)$}},
 xmajorgrids,ymajorgrids,grid style={{gray!18}},
 tick label style={{font=\\footnotesize}},label style={{font=\\small}},
 legend style={{at={{(0.98,0.98)}},anchor=north east,font=\\scriptsize}}]
\\addplot[actblue,thick] coordinates {{ {c1} }};
\\addlegendentry{{outage = censored (KM, tier 1)}}
\\addplot[actorange,thick,dashed] coordinates {{ {c3} }};
\\addlegendentry{{outage = worst-case failure (tier 3)}}
% censoring ticks on the tier-1 curve
\\addplot[only marks,mark=|,mark size=2.6pt,color=actblue!70]
  coordinates {{ {" ".join(f"({t:.1f},{s:.4f})" for t, s in (t1.get("curve") or [])[-min(len(t1.get("curve") or []), 12):])} }};
\\addlegendentry{{censoring events (outage)}}
\\end{{axis}}
\\end{{tikzpicture}}}}%
\\caption{{Time-to-verdict under the two extreme outage treatments; the
competing-risk view (tier 2) is in the text. Every qualitative curve claim
must hold under both envelopes and the tier-2 view before it enters the
paper.}}
\\label{{fig:kmband}}
\\end{{figure}}
"""
    args.out.write_text(tex)
    print(f"written: {args.out}  (tier1 n={t1.get('n')}, tier3 n={t3.get('n')}, xmax={xmax:.0f}s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
