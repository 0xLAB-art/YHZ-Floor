# Read instance
with open(sys.argv[1], 'r') as f:
    instance = json.load(f)

# Parse signatures
sig1 = instance['signatures'][0]
sig2 = instance['signatures'][1]

r = int(sig1['r'], 16)
s1 = int(sig1['s'], 16)
z1 = int(sig1['z'], 16)
s2 = int(sig2['s'], 16)
z2 = int(sig2['z'], 16)

# Recover nonce k
# k = (z1 - z2) / (s1 - s2) mod n
z_diff = (z1 - z2) % n
s_diff = (s1 - s2) % n
k = (z_diff * modinv(s_diff, n)) % n

# Recover private key d
# d = (s*k - z) / r mod n
d = ((s1 * k - z1) * modinv(r, n)) % n

# Format as 64 hex characters
d_hex = format(d, '064x')

