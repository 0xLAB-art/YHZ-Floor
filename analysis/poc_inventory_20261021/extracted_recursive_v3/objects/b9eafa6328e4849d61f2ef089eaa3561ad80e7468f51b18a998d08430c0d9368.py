INV_S_BOX = [0]*256
for i, v in enumerate(S_BOX):
    INV_S_BOX[v] = i

def recover_key_byte(byte_pos, base_pt):
    """Recover key byte at position byte_pos (0-15) using base_pt for other positions."""
    table = byte_pos % 4  # 0,1,2,3
    all_table_pages = []  # list of sets of pages in target table for each v
    for v in range(256):
        pt = bytearray(base_pt)
        pt[byte_pos] = v
        encrypt(bytes(pt))
        fp = get_footprint()
        pages = fp["pages"]
        table_pages = {p for p in pages if p // 256 == table}
        all_table_pages.append(table_pages)
    # Fixed pages are intersection of all queries
    fixed_pages = set.intersection(*all_table_pages) if all_table_pages else set()
    # Find a v with a varying page
    for v, pages in enumerate(all_table_pages):
        varying = pages - fixed_pages
        if len(varying) == 1:
            page = varying.pop()
            index = page % 256
            key_byte = v ^ INV_S_BOX[index]
            return key_byte
    # If all collide (should not happen), fallback: use frequency analysis
    # Count frequencies of pages across all queries
    freq = {}
    for pages in all_table_pages:
        for p in pages:
            freq[p] = freq.get(p, 0) + 1
    # Pages with frequency 1 are varying pages (should be 256 - len(fixed_pages))
    varying_pages = {p for p, cnt in freq.items() if cnt == 1}
    if varying_pages:
        # pick any varying page, find its v
        for v, pages in enumerate(all_table_pages):
            for p in pages:
                if p in varying_pages:
                    index = p % 256
                    return v ^ INV_S_BOX[index]
    raise Exception(f"Failed to recover key byte {byte_pos}")

def main():
    # Use all-zero base plaintext
    base_pt = bytes(16)
    key_bytes = []
    for i in range(16):
        kb = recover_key_byte(i, base_pt)
        key_bytes.append(kb)
        print(f"Key byte {i}: {kb:02x}", file=sys.stderr)
    key_hex = ''.join(f'{b:02x}' for b in key_bytes)
    print(f"Recovered key: {key_hex}", file=sys.stderr)
    # Output claim
    print(f'CLAIM:{{"key_hex": "{key_hex}"}}')

